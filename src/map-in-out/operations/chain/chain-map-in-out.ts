export function chainMapInOut(...maps: MapInOut<unknown, unknown>[]): MapInOut<unknown, unknown> {
  return Object.freeze({
    inOut: (value: unknown): unknown => {
      return maps.reduce(
        (value: unknown, map: MapInOut<unknown, unknown>): unknown => map.inOut(value),
        value,
      );
    },
    outIn: (value: unknown): unknown => {
      return maps.reduceRight(
        (value: unknown, map: MapInOut<unknown, unknown>): unknown => map.outIn(value),
        value,
      );
    },
  });
}
